create table if not exists uav_downward_photo_clip (
  id bigint primary key auto_increment,
  scan_date date not null,
  product_key varchar(64) not null default '',
  device_id varchar(128) not null,
  sn varchar(128),
  video_id varchar(256),
  payload_index varchar(64),
  clip_start datetime(3) not null default '1970-01-01 00:00:00.000',
  clip_end datetime(3) not null default '1970-01-01 00:00:00.000',
  clip_url varchar(1024),
  calibration_task_id varchar(128),
  calibration_status varchar(32),
  calibration_camera_sn varchar(128),
  calibration_camera_mode varchar(32),
  calibration_error varchar(1024),
  control_center_properties_url varchar(1024),
  property_snapshot_time datetime(3),
  condition_summary json,
  rule_version varchar(64) not null,
  status varchar(32) not null,
  error_message varchar(1024),
  created_at datetime(3) not null,
  updated_at datetime(3) not null,
  unique key uk_clip_rule (device_id, video_id, clip_start, clip_end, rule_version),
  key idx_scan_status (scan_date, status),
  key idx_calibration_status (calibration_status),
  key idx_device_scan (device_id, scan_date),
  key idx_device_calibration_recent (device_id, status, created_at)
);
